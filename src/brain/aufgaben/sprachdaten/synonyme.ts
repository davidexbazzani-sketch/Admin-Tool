// Synonyme und Gegenteile — selbst geschriebene Aufgaben.
// Jede Aufgabe: Schwierigkeitslage t (1 = Alltagswörter … 5 = Bildungswortschatz), das Ausgangswort,
// die richtige Antwort, mindestens drei falsche Antworten und (ab Lage 3) die Bedeutung in Stichworten.
// Regeln beim Schreiben:
//  • Keine falsche Antwort ist selbst ein Synonym (bei „syn“) bzw. ein Gegenteil (bei „geg“) des Ausgangsworts.
//  • Ab Lage 3 sind „Beinahe-Treffer“ dabei: verwandte Bedeutung mit anderer Färbung oder ähnlich klingende Wörter.
//  • Jedes Ausgangswort kommt nur einmal vor.
import type { Lage } from './analogien'

export interface WortPaar {
  t: Lage
  art: 'syn' | 'geg'
  /** Ausgangswort */
  w: string
  /** richtige Antwort */
  r: string
  /** falsche Antworten (mindestens drei) */
  f: string[]
  /** Bedeutung des Ausgangsworts in Stichworten */
  b?: string
}

const S = (t: Lage, w: string, r: string, falsch: string, b?: string): WortPaar => ({ t, art: 'syn', w, r, f: falsch.split('|'), b })
const G = (t: Lage, w: string, r: string, falsch: string, b?: string): WortPaar => ({ t, art: 'geg', w, r, f: falsch.split('|'), b })

